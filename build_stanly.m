function buildResults = build_stanly()
%BUILD_STANLY Build a Windows GUI executable and installer with MATLAB Compiler.
root = fileparts(mfilename('fullpath'));
if ~license('test','Compiler')
    error('Stanly:CompilerLicense','MATLAB Compiler is required to build STANLY.');
end
addpath(fullfile(root,'src'));
if ~ispc
    error('Stanly:BuildPlatform','Build this Windows package on Windows.');
end
buildResults = compiler.build.standaloneWindowsApplication(fullfile(root,'stanly.m'), ...
    'ExecutableName','StanlyFEA', ...
    'AdditionalFiles',{fullfile(root,'src'),fullfile(root,'install_path'),fullfile(root,'examples')}, ...
    'OutputDir',fullfile(root,'build','application'), ...
    'Verbose','on');
compiler.package.installer(buildResults, ...
    'ApplicationName','Stanly FEA', ...
    'InstallerName','StanlyFEAInstaller', ...
    'RuntimeDelivery','web', ...
    'OutputDir',fullfile(root,'build','installer'));
end
